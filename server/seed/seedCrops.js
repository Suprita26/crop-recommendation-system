// Give every crop without a real photo a placeholder (brand-colored, labeled
// with the crop name) so the UI never shows a broken image out of the box.
// Replace any of these anytime from the admin "Manage Crops" screen -- just
// paste an image URL, or point it at another file in client/public/crop-images/.
const PLACEHOLDER_BG = "2F5233"; // matches --color-primary in the client theme
const PLACEHOLDER_FG = "F7F3EA"; // matches --color-bg in the client theme
crops.forEach((crop) => {
  if (!crop.imageUrl) {
    const label = encodeURIComponent(crop.name);
    crop.imageUrl = `https://placehold.co/640x420/${PLACEHOLDER_BG}/${PLACEHOLDER_FG}?text=${label}&font=raleway`;
  }
});

(async () => {
  try {
    await connectDB();
    await Crop.deleteMany({});
    const inserted = await Crop.insertMany(crops);
    console.log(`Seeded ${inserted.length} crops successfully.`);
    process.exit(0);
  } catch (err) {
    console.error("Seeding failed:", err.message);
    process.exit(1);
  }
})();
